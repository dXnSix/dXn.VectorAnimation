#!/usr/bin/env python3
"""Generates `src/defs.rs`, the Rive types and properties the importer knows,
from rive-runtime's core definitions (`dev/defs`).

    python3 tools/defs.py <rive-runtime checkout> <its tag> > src/defs.rs

The definitions are rive-runtime's (MIT, Copyright 2020 Rive). What the
runtime leaves out (`"runtime": false`) is left out here too, so the importer
treats it as the runtime does: as an unknown object or property.
"""

import glob
import json
import os
import re
import sys

FIELDS = {
    "uint": "Uint",
    "bool": "Bool",
    "double": "Double",
    "String": "String",
    "Bytes": "Bytes",
    "Color": "Color",
}


def snake(name):
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return name.upper()


def initial(field, value):
    """The initial value as an f64 literal, for numbers, bools and colors."""
    if value is None:
        return None
    value = str(value)
    if field == "Bool":
        return {"true": "1.0", "false": "0.0"}.get(value)
    if field == "Color":
        return "%.1f" % int(value, 16 if value.startswith("0x") else 10)
    if field in ("Uint", "Double"):
        if field == "Uint" and value in ("-1", "Core.missingId"):
            return "%.1f" % 0xFFFFFFFF
        if value == "CoreContext.invalidPropertyKey":
            return "0.0"
        try:
            return repr(float(value))
        except ValueError:
            return None
    return None


def main():
    root, tag = sys.argv[1], sys.argv[2]
    base = os.path.join(root, "dev", "defs")
    defs = {}
    for path in glob.glob(os.path.join(base, "**", "*.json"), recursive=True):
        with open(path) as f:
            defs[os.path.relpath(path, base)] = json.load(f)

    types, props, alternates, editor = [], [], [], []
    for rel, d in defs.items():
        if d.get("runtime") is False:
            editor.append(d["key"]["int"])
            continue
        parent = d.get("extends")
        parent_key = None
        if parent and defs[parent].get("runtime") is not False:
            parent_key = defs[parent]["key"]["int"]
        types.append((d["key"]["int"], d["name"], parent_key, bool(d.get("abstract"))))
        for name, p in d.get("properties", {}).items():
            if p.get("runtime") is False:
                continue
            field = FIELDS.get(p.get("typeRuntime") or p["type"])
            if field is None:
                continue
            value = p.get("initialValueRuntime", p.get("initialValue"))
            key = p["key"]["int"]
            const = snake(d["name"]) + "_" + snake(name[0].upper() + name[1:])
            props.append((key, const, field, initial(field, value), d["name"] + "." + name))
            for alt in p["key"].get("alternates", []):
                alternates.append((alt["int"], key))

    types.sort()
    props.sort()
    out = []
    w = out.append
    w("//! The Rive types and properties the importer knows: generated by")
    w("//! `tools/defs.py` from rive-runtime's core definitions at `%s`" % tag)
    w("//! (MIT, Copyright 2020 Rive). Do not edit.")
    w("")
    w("#![allow(dead_code, missing_docs)]")
    w("")
    w("/// The rive-runtime tag the tables follow.")
    w('pub const RUNTIME_TAG: &str = "%s";' % tag)
    w("")
    w("/// How a property's value is written.")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    w("pub enum Field {")
    for f in ["Uint", "Bool", "Double", "String", "Bytes", "Color"]:
        w("    %s," % f)
    w("}")
    w("")
    w("/// Type keys.")
    w("pub mod types {")
    for key, name, _, _ in types:
        w("    pub const %s: u16 = %d;" % (snake(name), key))
    w("}")
    w("")
    w("/// Property keys.")
    w("pub mod props {")
    for key, const, _, _, _ in props:
        w("    pub const %s: u16 = %d;" % (const, key))
    w("}")
    w("")
    w("/// The type `ty` extends, if any.")
    w("pub fn parent(ty: u16) -> Option<u16> {")
    w("    match ty {")
    for key, _, parent, _ in types:
        if parent is not None:
            w("        %d => Some(%d)," % (key, parent))
    w("        _ => None,")
    w("    }")
    w("}")
    w("")
    w("/// The name of type `ty`, when the runtime knows it.")
    w("pub fn type_name(ty: u16) -> Option<&'static str> {")
    w("    Some(match ty {")
    for key, name, _, _ in types:
        w('        %d => "%s",' % (key, name))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    w("/// Whether type `ty` is the editor's alone: in files, but left out by")
    w("/// the runtime as by the importer.")
    w("pub fn is_editor_only(ty: u16) -> bool {")
    w("    matches!(ty, %s)" % " | ".join(str(k) for k in sorted(editor)))
    w("}")
    w("")
    w("/// Whether type `ty` is only a base of others (never in a file).")
    w("pub fn is_abstract(ty: u16) -> bool {")
    abstract = [str(k) for k, _, _, a in types if a]
    w("    matches!(ty, %s)" % " | ".join(abstract))
    w("}")
    w("")
    w("/// How property `key` is written, when the runtime knows it.")
    w("pub fn field(key: u16) -> Option<Field> {")
    w("    Some(match key {")
    for field in FIELDS.values():
        keys = [str(k) for k, _, f, _, _ in props if f == field]
        if keys:
            w("        %s => Field::%s," % (" | ".join(keys), field))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    w("/// The value property `key` has when an object does not write it: numbers,")
    w("/// bools (0 or 1) and colors (ARGB).")
    w("pub fn initial(key: u16) -> Option<f64> {")
    w("    Some(match key {")
    by_value = {}
    for k, _, _, v, _ in props:
        if v is not None:
            by_value.setdefault(v, []).append(str(k))
    for v, keys in sorted(by_value.items(), key=lambda kv: float(kv[0])):
        w("        %s => %s," % (" | ".join(keys), v if "." in v or "e" in v else v + ".0"))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    w("/// The name of property `key` (`Type.property`), when the runtime knows it.")
    w("pub fn prop_name(key: u16) -> Option<&'static str> {")
    w("    Some(match key {")
    for k, _, _, _, n in props:
        w('        %d => "%s",' % (k, n))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    w("/// The key older files write for property `key`'s current one.")
    w("pub fn canonical(key: u16) -> u16 {")
    w("    match key {")
    for alt, key in sorted(alternates):
        w("        %d => %d," % (alt, key))
    w("        _ => key,")
    w("    }")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
